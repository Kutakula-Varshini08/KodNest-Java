
class ConcatMethodInString {

    public static void main(String[] args) {
        String s1 = "Varshini";
        String s2 = "Tanusha";
        String s3 = s1 + s2;
        System.out.println(s3);
        String t1 = new String("Varu");
        String t2 = new String("Tanu");
        String t3 = t1.concat(t2);
        System.out.println(t3);
    }
}
